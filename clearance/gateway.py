"""Clearance Gateway MCP server. Claude talks to this; this talks to BioMCP.

Run: python -m clearance.gateway --model demo-model --path replicating --data-dir run
"""
import argparse
import itertools
import shutil
import sys
from pathlib import Path

from mcp.server.mcpserver import MCPServer

from . import gates, policy, state as state_mod, stopping
from .audit import AuditLog
from .biomcp_proxy import BioMCPProxy
from .redact import redact

mcp = MCPServer("clearance-gateway")
ROLES = ("regulator", "bsl4_staff", "bsl3_staff", "accredited", "public")
STUB = "[DEMO STUB: no sequence is ever generated by this gateway]"


class Runtime:
    def __init__(self, data_dir: Path, model: str, model_path: str, biomcp_cmd: str) -> None:
        self.state_path = Path(data_dir) / "state.json"
        self.state = state_mod.load(self.state_path, model, model_path)
        self.audit = AuditLog(Path(data_dir) / "audit.jsonl")
        self.proxy = BioMCPProxy(biomcp_cmd)
        self.who: dict[str, str] = {}
        self.denied_tools: set[str] = set()
        self.design_ids = itertools.count(1)

    def save(self) -> None:
        state_mod.save(self.state, self.state_path)


rt: Runtime | None = None


def configure(data_dir: Path, model: str, model_path: str, biomcp_cmd: str) -> Runtime:
    global rt
    rt = Runtime(data_dir, model, model_path, biomcp_cmd)
    return rt


def _signal(kind: str) -> None:
    rt.state.signals[kind] += 1


def _gate(tool: str, entity: str | None = None) -> policy.Decision:
    """Policy check plus content-free signal bookkeeping. Logs who, what tool, and the verdict only."""
    if not rt.who:
        return policy.Decision(False, "DENIED: identify yourself first with whoami")
    d = policy.decide(rt.state.phase, rt.who["role"], tool, entity, bool(rt.who.get("bio_id")))
    if not d.allowed:
        if tool in rt.denied_tools:
            _signal("retry_after_denial")
        rt.denied_tools.add(tool)
    rt.audit.append("tool_call", tool=tool, entity=entity, role=rt.who["role"],
                    bio_id=rt.who.get("bio_id") or None, allowed=d.allowed, phase=rt.state.phase)
    rt.save()
    return d


@mcp.tool()
def whoami(name: str, role: str, bio_id: str = "") -> str:
    """Set who is using the model: role is regulator | bsl4_staff | bsl3_staff | accredited | public."""
    if role not in ROLES:
        return f"Unknown role '{role}'. Use one of: {', '.join(ROLES)}"
    rt.who = {"name": name, "role": role, "bio_id": bio_id}
    rt.denied_tools.clear()
    rt.audit.append("whoami", name=name, role=role, bio_id=bio_id or None)
    return f"Session: {name} as {role}{' with bio login ' + bio_id if bio_id else ' (no bio login)'}."


@mcp.tool()
def clearance_status() -> str:
    """Phase, path, pre-registration, votes, signals vs. stopping boundary, power calculation."""
    s = rt.state
    lines = [f"Model: {s.model}  |  Path: {s.path}  |  {policy.PHASE_NAMES[s.phase]}",
             f"Cleared roles: {', '.join(sorted(policy.ROLES_BY_PHASE[s.phase]))}"]
    if s.prereg:
        p = s.prereg
        lines += [f"Pre-registered by {p.registered_by}: {p.criteria}",
                  f"Stopping rule: baseline {p.baseline_per_user_week}/user-week, detect x{p.rate_ratio}, "
                  f"alpha {p.alpha} over {p.planned_looks} looks ({p.alpha_per_look:.4f} per look)",
                  f"Power: ~{stopping.required_user_weeks(p):,} user-weeks needed before the rule could fire (80% power)"]
    else:
        lines.append("Pre-registration: NONE (no votes accepted until criteria are registered)")
    lines.append(f"Exposure: {s.user_weeks:,.0f} user-weeks, looks used {s.looks_used}")
    lines.append("Proxy signals (content-free): " + ", ".join(f"{k}={v}" for k, v in s.signals.items()))
    lines.append(f"Votes: {len(s.votes)}/{gates.QUORUM} " + "; ".join(f"{v.name}={v.decision}" for v in s.votes))
    ok, bad = rt.audit.verify()
    lines.append(f"Audit chain: {'intact' if ok else f'BROKEN at entry {bad}'}")
    return "\n".join(lines)


@mcp.tool()
def preregister_phase(criteria: str, baseline_per_user_week: float, rate_ratio: float,
                      alpha: float = 0.05, planned_looks: int = 4) -> str:
    """Regulator registers pass/hold/back criteria and the stopping rule before votes."""
    if rt.who.get("role") != "regulator":
        return "DENIED: only the regulator can pre-register criteria"
    prereg = stopping.Prereg(rt.state.phase, criteria, baseline_per_user_week, rate_ratio,
                             alpha, planned_looks, rt.who["name"])
    try:
        gates.preregister(rt.state, prereg)
    except gates.GateError as e:
        return f"REFUSED: {e}"
    rt.audit.append("preregister", phase=rt.state.phase, criteria=criteria, baseline=baseline_per_user_week,
                    rate_ratio=rate_ratio, alpha=alpha, planned_looks=planned_looks, by=rt.who["name"])
    rt.save()
    return f"Registered for {policy.PHASE_NAMES[rt.state.phase]}. Rule needs ~{stopping.required_user_weeks(prereg):,} user-weeks for 80% power."


@mcp.tool()
def cast_gate_vote(evaluator_name: str, evaluator_role: str, decision: str, rationale: str) -> str:
    """Named evaluator vote: forward | hold | back. Applied at 5 votes (3 needed to move)."""
    try:
        outcome = gates.cast_vote(rt.state, evaluator_name, evaluator_role, decision, rationale)
    except gates.GateError as e:
        return f"REFUSED: {e}"
    rt.audit.append("vote", name=evaluator_name, role=evaluator_role, decision=decision, rationale=rationale)
    if outcome is None:
        rt.save()
        return f"Vote recorded ({len(rt.state.votes)}/{gates.QUORUM})."
    rt.audit.append("gate_outcome", decision=outcome.decision, from_phase=outcome.from_phase,
                    to_phase=outcome.to_phase, tally=outcome.tally)
    rt.denied_tools.clear()
    rt.save()
    return (f"GATE {outcome.decision.upper()} {outcome.tally}: {policy.PHASE_NAMES[outcome.from_phase]} -> "
            f"{policy.PHASE_NAMES[outcome.to_phase]}")


@mcp.tool()
async def bio_search(entity: str, query: str = "", gene: str = "", disease: str = "", limit: int = 5) -> str:
    """Search BioMCP (article, trial, gene, protein, variant, ...) if cleared for this phase and role."""
    d = _gate("bio_search", entity)
    if not d.allowed:
        return d.reason
    args = {"entity": entity, "limit": limit, **{k: v for k, v in
            {"query": query, "gene": gene, "disease": disease}.items() if v}}
    text, is_error = await rt.proxy.call("search", args)
    return ("BioMCP error: " if is_error else "") + redact(text).text


@mcp.tool()
async def bio_get(entity: str, id: str) -> str:
    """Get one BioMCP record (gene, article, trial, drug, ...) if cleared for this phase and role."""
    d = _gate("bio_get", entity)
    if not d.allowed:
        return d.reason
    text, is_error = await rt.proxy.call("get", {"entity": entity, "id": id})
    return ("BioMCP error: " if is_error else "") + redact(text).text


@mcp.tool()
def design_stub(purpose: str) -> str:
    """Stand-in for novel sequence design. Never returns a sequence. Every attempt, cleared or not, is a signal."""
    _signal("design_stub")
    d = _gate("design_stub")
    if not d.allowed:
        return d.reason
    return f"{STUB} design_id=D-{next(rt.design_ids):04d} logged to {rt.who.get('bio_id') or rt.who['name']}"


@mcp.tool()
def export_design(design_id: str) -> str:
    """Send a design outside the container. Denied below full clearance. Every attempt is a signal."""
    _signal("export_attempt")
    d = _gate("export_design")
    return d.reason if not d.allowed else f"Export of {design_id} recorded (demo: nothing leaves)."


@mcp.tool()
def ingest_synthetic_traffic(user_weeks: float, signals: int) -> str:
    """Demo driver: add synthetic exposure and proxy signals, then run a scheduled stopping-rule look."""
    s = rt.state
    if s.prereg is None:
        return "REFUSED: no stopping rule registered for this phase"
    if s.looks_used >= s.prereg.planned_looks:
        return (f"REFUSED: all {s.prereg.planned_looks} pre-registered looks are used; "
                "the board must vote (forward / hold / back) before more monitoring counts")
    s.user_weeks += user_weeks
    s.signals["synthetic"] += signals
    s.looks_used += 1
    v = stopping.check(s.prereg, s.user_weeks, s.total_signals(), s.looks_used)
    rt.audit.append("look", look=v.look, expected=round(v.expected, 3), observed=v.observed,
                    p_value=v.p_value, fired=v.fired)
    msg = (f"Look {v.look}: observed {v.observed} vs expected {v.expected:.1f} "
           f"(p={v.p_value:.4g}, threshold {v.alpha_per_look:.4f}).")
    if v.fired:
        outcome = gates.step_back(s)
        rt.denied_tools.clear()
        rt.audit.append("clinical_hold", from_phase=outcome.from_phase, to_phase=outcome.to_phase)
        msg += (f"\nSTOPPING RULE FIRED. Clinical hold: {policy.PHASE_NAMES[outcome.from_phase]} -> "
                f"{policy.PHASE_NAMES[outcome.to_phase]}. Tools re-gated now.")
    else:
        msg += " Rule not fired; phase continues."
    rt.save()
    return msg


@mcp.tool()
def verify_audit() -> str:
    """Check the hash chain of the audit log."""
    ok, bad = rt.audit.verify()
    n = len(rt.audit.entries())
    return f"Audit chain intact ({n} entries)." if ok else f"AUDIT CHAIN BROKEN at entry {bad} of {n}."


def _default_biomcp() -> str:
    """Prefer the biomcp installed next to this Python (the project venv) over any on PATH."""
    local = Path(sys.executable).parent / "biomcp"
    return str(local) if local.exists() else (shutil.which("biomcp") or "biomcp")


def main() -> None:
    ap = argparse.ArgumentParser(description="Clearance Gateway MCP server")
    ap.add_argument("--model", default="demo-model")
    ap.add_argument("--path", default="replicating", choices=list(policy.PATH_ORDER))
    ap.add_argument("--data-dir", default="run")
    ap.add_argument("--biomcp", default=_default_biomcp())
    args = ap.parse_args()
    configure(Path(args.data_dir), args.model, args.path, args.biomcp)
    mcp.run()


if __name__ == "__main__":
    main()
